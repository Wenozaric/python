from fnmatch import fnmatch

#* - беск кол-во цифр может быть
#? - одна какая-то цифра

print(fnmatch('1234567', '123?7'))

b = 17

d = []

while b < 1000000000:
    if fnmatch(str(b), '12345?6?8'): d.append([b, b // 17])
    b += 17
# 12345?6?8
#[[123450668, 7261804], [123451688, 7261864], [123456618, 7262154], [123457638, 7262214], [123458658, 7262274], [123459678, 7262334]]

print(d)